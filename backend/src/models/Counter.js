const mongoose = require('mongoose');

// Atomic sequence generator, used for human-friendly IDs like EMP-0001.
// findOneAndUpdate with $inc is atomic, so two simultaneous requests never get the same number.
const counterSchema = new mongoose.Schema({
  _id: { type: String, required: true },
  seq: { type: Number, default: 0 },
});

counterSchema.statics.next = async function next(name) {
  const counter = await this.findOneAndUpdate(
    { _id: name },
    { $inc: { seq: 1 } },
    { new: true, upsert: true }
  );
  return counter.seq;
};

module.exports = mongoose.model('Counter', counterSchema);
